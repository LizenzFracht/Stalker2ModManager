// Generates THIRD_PARTY_NOTICES.md from the license files of every Rust crate and npm
// package that ends up in the app. Identical license texts are printed once.
//   node scripts/third-party-notices.mjs
import { execSync } from "node:child_process";
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const LICENSE_FILE = /^(licen[cs]e|copying|notice|unlicense)([-_.].*)?$/i;

function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((f) => LICENSE_FILE.test(f))
    .sort()
    .map((f) => readFileSync(join(dir, f), "utf8").replace(/\r\n/g, "\n").trim())
    .filter(Boolean);
}

// ---------------------------------------------------------------- Rust
const host = execSync("rustc -vV", { encoding: "utf8" }).match(/host: (\S+)/)[1];
const meta = JSON.parse(
  execSync(`cargo metadata --format-version 1 --locked --filter-platform ${host} --manifest-path src-tauri/Cargo.toml`, {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 1 << 28,
  }),
);
const pkgs = new Map(meta.packages.map((p) => [p.id, p]));
const nodes = new Map(meta.resolve.nodes.map((n) => [n.id, n]));
const seen = new Set();
const stack = [meta.resolve.root];
while (stack.length) {
  const id = stack.pop();
  if (seen.has(id)) continue;
  seen.add(id);
  for (const d of nodes.get(id).deps) {
    if (d.dep_kinds.some((k) => k.kind === null || k.kind === "build")) stack.push(d.pkg);
  }
}
seen.delete(meta.resolve.root);

const components = [];
for (const id of seen) {
  const p = pkgs.get(id);
  const dir = dirname(p.manifest_path);
  components.push({
    name: p.name,
    version: p.version,
    license: p.license ?? "see license file",
    url: p.repository ?? `https://crates.io/crates/${p.name}`,
    texts: licenseTexts(dir),
  });
  // unrar_sys bundles RARLAB's UnRAR source under its own license.
  if (p.name === "unrar_sys") {
    const unrar = join(dir, "vendor/unrar/license.txt");
    if (existsSync(unrar)) {
      components.push({
        name: "UnRAR (bundled in unrar_sys)",
        version: "",
        license: "UnRAR license (freeware)",
        url: "https://www.rarlab.com/",
        texts: [readFileSync(unrar, "utf8").replace(/\r\n/g, "\n").trim()],
      });
    }
  }
}

// ---------------------------------------------------------------- npm
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path || info.dev) continue;
  const name = path.split("node_modules/").pop();
  const dir = join(root, path);
  let url = `https://www.npmjs.com/package/${name}`;
  try {
    const pj = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
    const repo = typeof pj.repository === "string" ? pj.repository : pj.repository?.url;
    if (repo) url = repo.replace(/^git\+/, "").replace(/\.git$/, "");
  } catch {}
  components.push({ name, version: info.version, license: info.license ?? "see license file", url, texts: licenseTexts(dir) });
}

// Fall back to another component's text with the same license expression.
const byLicense = new Map();
for (const c of components) if (c.texts.length && !byLicense.has(c.license)) byLicense.set(c.license, c.texts);
for (const c of components) if (!c.texts.length && byLicense.has(c.license)) c.texts = byLicense.get(c.license), (c.borrowed = true);

components.sort((a, b) => a.name.localeCompare(b.name));
const textIds = new Map();
const texts = [];
for (const c of components) {
  c.refs = c.texts.map((t) => {
    if (!textIds.has(t)) {
      textIds.set(t, texts.length + 1);
      texts.push({ text: t, users: [] });
    }
    const id = textIds.get(t);
    texts[id - 1].users.push(`${c.name}${c.version ? " " + c.version : ""}`);
    return id;
  });
}

let md = `# Third-party notices

S2MM is MIT licensed (see \`LICENSE\`). It includes the open-source components listed
below; their licenses follow at the end of this file. This file is generated by
\`scripts/third-party-notices.mjs\`.

## Downloaded or used at runtime (not bundled)

| Component | License | Notes |
| --- | --- | --- |
| [UE4SS](https://github.com/UE4SS-RE/RE-UE4SS) | MIT | Downloaded from GitHub on request, including the Stalker 2 config from \`zCustomGameConfigs\`. |
| [joric's Stalker 2 interactive map](https://github.com/joric/stalker) | Unlicense | Map page, data and tiles are loaded from joric.github.io by the local live-map server and cached on the user's PC. |
| [Mod Configuration Menu (MCM)](https://www.nexusmods.com/stalker2heartofchornobyl/search/?gsearch=Mod%20Configuration%20Menu) | by its authors | Not bundled – S2MM only reads and writes the settings file MCM creates. |

## Bundled components (${components.length})

| Component | Version | License | License text |
| --- | --- | --- | --- |
`;
for (const c of components) {
  md += `| [${c.name}](${c.url}) | ${c.version} | ${c.license} | ${c.refs.map((r) => `[#${r}](#license-${r})`).join(", ") || "–"}${c.borrowed ? " ¹" : ""} |\n`;
}
md += `\n¹ No license file shipped with the package; the standard text of the stated license applies.\n\n## License texts\n`;
texts.forEach((t, i) => {
  const users = t.users.length > 12 ? `${t.users.slice(0, 12).join(", ")} and ${t.users.length - 12} more` : t.users.join(", ");
  md += `\n### License ${i + 1}\n<a id="license-${i + 1}"></a>\n\nUsed by: ${users}\n\n\`\`\`text\n${t.text}\n\`\`\`\n`;
});
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), md);
console.log(`THIRD_PARTY_NOTICES.md: ${components.length} components, ${texts.length} distinct license texts`);
